// The school admin's own routes (ADMIN.md): tree, people, staff, analytics,
// settings. Mounted inside routes/admin.js after adminAuth + orgContext, so every
// handler has req.org (the caller's school only) and req.actor. Each route states
// its permission (utils/orgAccess.js) and, where a plan module owns the feature,
// requireModule(...).
const express = require('express')
const multer = require('multer')
const router = express.Router()
const { permit, adminOnly } = require('../utils/orgAccess')
const { requireModule } = require('../utils/entitlements')
const s = require('../controllers/schoolController')
const a = require('../controllers/schoolAnalyticsController')
const g = require('../controllers/schoolSettingsController')

const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 5 * 1024 * 1024, files: 1 } })
const oneFile = (req, res, next) => upload.single('file')(req, res, (err) => {
  if (err) return res.status(400).json({ success: false, message: err.code === 'LIMIT_FILE_SIZE' ? 'The file is over 5 MB.' : 'Upload one .csv or .xlsx file.' })
  next()
})
const tree = requireModule('org.tree')
const analytics = requireModule('org.analytics')

router.get('/access', permit(), s.access)
router.get('/status', permit(), g.status)
router.get('/setup', adminOnly, g.setup)

// School tree (ADM-010/011) and years (ADM-012)
router.get('/units', permit('tree.read'), tree, s.getTree)
router.post('/units', adminOnly, tree, s.createUnit)
router.post('/units/bulk', adminOnly, tree, s.bulkCreateUnits)
router.patch('/units/:id', adminOnly, tree, s.updateUnit)
router.delete('/units/:id', adminOnly, tree, s.deleteUnit)
router.get('/units/:id/people', permit('people.read'), tree, s.unitPeople)
router.post('/units/:id/assign', permit('people.read'), tree, s.assignToUnit)
router.get('/years', permit('settings.read'), s.listYears)
router.post('/years', adminOnly, s.createYear)
router.patch('/years/:id', adminOnly, s.updateYear)
router.get('/promotion/suggest', adminOnly, tree, s.promotionSuggest)
router.post('/promotion/preview', adminOnly, tree, s.promotionPreview)
router.post('/promotion/apply', adminOnly, tree, s.promotionApply)

// People (ADM-020/022/024/025)
router.get('/people/students', permit('people.read'), s.listStudents)
router.get('/import/template', permit('people.import'), s.importTemplate)
router.post('/import/upload', permit('people.import'), oneFile, s.importUpload)
router.post('/import/:id/preview', permit('people.import'), s.importPreview)
router.post('/import/:id/commit', permit('people.import'), s.importCommit)
router.get('/invites', permit('parents.invite'), s.listInvites)
router.post('/invites', permit('parents.invite'), s.sendInvites)
router.post('/students/:id/move', permit('people.move'), s.moveStudent)
router.get('/students/:id/history', permit('people.read'), s.studentHistory)
router.post('/students/:id/leave', permit('people.write'), s.markLeaver)
router.post('/students/:id/rejoin', permit('people.write'), s.rejoin)
router.get('/students/:id/profile', permit('analytics.read'), a.studentProfile)
router.post('/tutors/:id/transfer', permit('people.write'), s.transferTeacher)
router.get('/seats', permit('people.read'), s.seats)

// Staff roles (ADM-023)
router.get('/staff', adminOnly, requireModule('staff.roles'), s.listStaff)
router.post('/staff', adminOnly, requireModule('staff.roles'), s.addStaff)
router.patch('/staff/:id', adminOnly, requireModule('staff.roles'), s.updateStaff)
router.delete('/staff/:id', adminOnly, requireModule('staff.roles'), s.removeStaff)

// School analytics (ADM-040..045)
router.get('/school/overview', permit('analytics.read'), analytics, a.overview)
router.get('/school/teachers', permit('analytics.read'), analytics, a.teachers)
router.get('/school/compare', permit('analytics.read'), analytics, a.compare)
router.get('/school/lists', permit('analytics.read'), analytics, a.lists)
router.get('/school/usage', permit('analytics.read'), analytics, a.usage)
router.get('/school/tests', permit('analytics.read'), analytics, a.tests)

// Question review (ADM-050) and school bank (ADM-051)
router.get('/review', permit('questions.review'), g.reviewQueue)
router.get('/review/:id', permit('questions.review'), g.reviewDetail)
router.post('/review/:id/notes', permit('questions.review'), g.addNote)
router.post('/review/bulk', permit('questions.review'), g.bulkReview)
router.get('/bank', permit('questions.review'), g.bank)
router.put('/bank/:id/tags', permit('questions.review'), g.tagBank)

// Policies, branding, billing, privacy, audit (ADM-060/061/080/081/082)
router.get('/policies', permit('settings.read'), g.getPolicies)
router.put('/policies', adminOnly, requireModule('comms.policy'), g.updatePolicies)
router.put('/branding', adminOnly, requireModule('reports.branded'), g.updateBranding)
router.get('/billing', adminOnly, g.billing)
router.get('/privacy', adminOnly, g.privacy)
router.post('/privacy/dpa', adminOnly, g.signDpa)
router.post('/privacy/consents', adminOnly, g.recordConsent)
router.get('/audit', adminOnly, g.auditLog)

module.exports = router
