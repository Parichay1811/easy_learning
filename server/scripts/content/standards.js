#!/usr/bin/env node
// The curriculum alignment of every skill (content v5), as a document for teachers, clinicians
// and buyers: docs/learning/STANDARDS.md, generated from skills-standards.json and skills-source.js,
// plus the compact copy the "Why Learnigo" page shows (client/src/data/standards.json).
//   node scripts/content/standards.js          write both
//   node scripts/content/standards.js --check  exit 1 if the document is out of date (used by the tests)
const fs = require('fs')
const path = require('path')
const SKILLS = require('./skills-source')
const STD = require('./skills-standards.json')

const OUT = path.resolve(__dirname, '../../../docs/learning/STANDARDS.md')
const cell = (s) => String(s ?? '–').replace(/\|/g, '/').replace(/\s+/g, ' ').trim() || '–'

function render() {
  const lines = []
  lines.push('# Curriculum alignment of every skill')
  lines.push('')
  lines.push('Generated by `server/scripts/content/standards.js` from `skills-standards.json` (do not edit by hand).')
  lines.push('')
  lines.push('Every question in the core bank practises one skill. This page maps each skill to the curriculum outcome it practises in Ireland, England and the US, to the CEFR (English) or the EU key competences (maths and science), and to adult literacy and numeracy levels. **Status: proposed.** The mappings were checked against the official documents listed at the end (on ' + STD.meta.generated + '). They become *reviewed* once a qualified teacher has read them. "Mapped to" means the skill practises that outcome. It does not mean a curriculum body endorses Learnigo.')
  lines.push('')
  lines.push('**Irish stages:** Stage 1 = Junior and Senior Infants, Stage 2 = 1st and 2nd class, Stage 3 = 3rd and 4th, Stage 4 = 5th and 6th (Primary Language Curriculum 2019, Primary Mathematics Curriculum 2023, Science, Technology and Engineering 2025). Junior Cycle covers the post-primary skills at maths levels 6-8.')
  lines.push('')
  const conf = {}
  for (const s of Object.values(STD.skills)) conf[s.confidence] = (conf[s.confidence] || 0) + 1
  lines.push(`**Confidence:** ${Object.entries(conf).map(([k, v]) => `${v} ${k}`).join(', ')}. A low-confidence mapping names the nearest strand where no outcome fits exactly.`)
  for (const subject of ['english', 'maths', 'science']) {
    lines.push('')
    lines.push(`## ${subject[0].toUpperCase()}${subject.slice(1)}`)
    lines.push('')
    lines.push('| Skill | Level | Ireland | England | US | CEFR / EU | Adults (NFQ / CCRS) |')
    lines.push('|---|---|---|---|---|---|---|')
    for (const sk of SKILLS.filter((x) => x.subject === subject).sort((a, b) => a.level - b.level || a.name.localeCompare(b.name))) {
      const m = STD.skills[sk.id] || {}
      const ie = m.ie ? `${m.ie.framework}: ${m.ie.outcome || m.ie.area}${m.ie.stage ? ` (Stage ${m.ie.stage})` : ''}` : ''
      const uk = m.uk ? `${m.uk.year}: ${m.uk.area}` : ''
      const us = m.us ? `${(m.us.codes || []).join(', ') || m.us.framework || ''} (grade ${m.us.grade || '–'})` : ''
      const eu = m.eu ? (m.eu.cefr ? `CEFR ${m.eu.cefr}` : m.eu.keyCompetence) : ''
      const ad = m.adult ? `NFQ ${m.adult.nfq} / CCRS ${m.adult.ccrs}` : ''
      lines.push(`| ${cell(sk.name)} | ${sk.level} | ${cell(ie)} | ${cell(uk)} | ${cell(us)} | ${cell(eu)} | ${cell(ad)} |`)
    }
  }
  lines.push('')
  lines.push('## Developmental order: changes made in content v5')
  lines.push('')
  lines.push('Where a skill was placed later than the curricula teach it, the skill (and its items) moved, so the ladder climbs in the order children develop:')
  lines.push('')
  for (const c of STD.levelConcerns) lines.push(`- **${c.skill}**: level ${c.currentLevel} → ${c.suggestedLevel}. ${cell(c.evidence)}`)
  lines.push('')
  lines.push('Kept on purpose: spelling aloud at level 4 (oral spelling loads working memory, which is hard for dyslexic learners); fractions, decimals and percentages at level 6 (US grade 6); powers at level 8 (the maths stretch levels).')
  lines.push('')
  lines.push('## Sources')
  lines.push('')
  for (const s of STD.sources) lines.push(`- ${cell(s.title)}${s.url ? ` (${s.url})` : ''}, checked ${s.checked || STD.meta.generated}`)
  return lines.join('\n') + '\n'
}

// The compact copy the "Why Learnigo" page shows (client/src/data/standards.json, loaded on demand).
const CLIENT_OUT = path.resolve(__dirname, '../../../client/src/data/standards.json')
function clientData() {
  const one = (m) => ({
    ie: m.ie ? { fw: m.ie.framework, text: m.ie.outcome || m.ie.area, stage: m.ie.stage ?? null, classes: m.ie.classes || '' } : null,
    uk: m.uk ? { text: `${m.uk.year}: ${m.uk.area}` } : null,
    us: m.us ? { codes: m.us.codes || [], grade: m.us.grade || '', fw: m.us.framework || '' } : null,
    eu: m.eu ? (m.eu.cefr ? { cefr: m.eu.cefr } : { text: m.eu.keyCompetence }) : null,
    adult: m.adult ? { nfq: m.adult.nfq, ccrs: m.adult.ccrs } : null,
  })
  return {
    generated: STD.meta.generated, status: 'proposed',
    skills: SKILLS.map((sk) => ({ id: sk.id, subject: sk.subject, name: sk.name, level: sk.level, ...one(STD.skills[sk.id] || {}) })),
    sources: STD.sources.map((x) => ({ title: x.title, url: x.url })),
  }
}
const clientText = () => JSON.stringify(clientData(), null, 1) + '\n'

if (require.main === module) {
  const text = render()
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    const nowClient = fs.existsSync(CLIENT_OUT) ? fs.readFileSync(CLIENT_OUT, 'utf8') : ''
    if (now !== text || nowClient !== clientText()) { console.error('STANDARDS.md or client/src/data/standards.json is out of date: run node scripts/content/standards.js'); process.exit(1) }
    console.log('STANDARDS.md and the client copy are up to date.')
  } else {
    fs.writeFileSync(OUT, text)
    fs.mkdirSync(path.dirname(CLIENT_OUT), { recursive: true })
    fs.writeFileSync(CLIENT_OUT, clientText())
    console.log(`Wrote ${path.relative(process.cwd(), OUT)} and the client copy (${SKILLS.length} skills).`)
  }
}
module.exports = { render, clientData }
