const get = (path) => path.split(".").reduce((o, k) => (o == null ? undefined : o[k]), STRINGS);

// t(`insights.${key}`) with the English default (and plural defaults) from STRINGS.
export function tx(t, key, params = {}) {
  const v = get(key);
  if (v && typeof v === "object" && "other" in v) {
    const count = params.count ?? 0;
    return t(`insights.${key}`, { defaultValue: count === 1 ? v.one : v.other, defaultValue_one: v.one, defaultValue_other: v.other, ...params, count });
  }
  return t(`insights.${key}`, { defaultValue: typeof v === "string" ? v : key, ...params });
}

export const hasString = (key) => get(key) !== undefined;

// Nested { insights: { …, key_one, key_other } } as i18next resources (for the translators' file).
export function toResources(node = STRINGS) {
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (v && typeof v === "object" && "other" in v && typeof v.other === "string") { out[`${k}_one`] = v.one; out[`${k}_other`] = v.other; }
    else if (v && typeof v === "object") out[k] = toResources(v);
    else out[k] = v;
  }
  return out;
}
